package codegentest

import (
	"os"
	"path/filepath"
	"strings"
	"time"
)

// SetGoFlags sets the GOFLAGS of the test process, which the go commands it runs inherit, for
// building generated programs: -trimpath, so that their builds in fresh temporary directories share
// the build cache, -mod=mod, so that the temporary modules that replace this module resolve it
// without a go.sum, and the tag sxir_feature_witness, so that every generated parser checks that its
// parses use only the library features that the generator's analysis found
// (codegen.GenOptions.FeatureWitness). The tag joins the tags of a -tags flag already in GOFLAGS,
// since the go command keeps only the last of repeated -tags flags.
func SetGoFlags() {
	os.Setenv("GOFLAGS", buildFlags(os.Getenv("GOFLAGS")))
}

// buildFlags returns goflags with the flags that SetGoFlags adds.
func buildFlags(goflags string) string {
	return WithWitnessTag(strings.TrimSpace(goflags + " -trimpath -mod=mod"))
}

// WithWitnessTag returns goflags, a GOFLAGS value, with the tag sxir_feature_witness added to the
// tags of its -tags flag, or with a -tags flag that names the tag if it has none.
func WithWitnessTag(goflags string) string {
	fields := strings.Fields(goflags)
	for i, f := range fields {
		for _, prefix := range []string{"-tags=", "--tags="} {
			if tags, ok := strings.CutPrefix(f, prefix); ok {
				if tags == "" {
					fields[i] = prefix + witnessTag
				} else {
					fields[i] = f + "," + witnessTag
				}
				return strings.Join(fields, " ")
			}
		}
	}
	return strings.TrimSpace(goflags + " " + WitnessTags)
}

// witnessTag is the build tag that turns on the check of the features of the generated parsers.
const witnessTag = "sxir_feature_witness"

// GoFlags are the flags of a go command that sets its GOFLAGS itself (GoFlagsEnv): the GOFLAGS of
// the test process when the package was initialized, with the flags that SetGoFlags adds.
var GoFlags = buildFlags(os.Getenv("GOFLAGS"))

// WitnessTags is the build flag that turns on the check of the features of the generated parsers
// (codegen.GenOptions.FeatureWitness), which every build of a parser generated by these helpers
// needs.
const WitnessTags = "-tags=" + witnessTag

// CorpusGCFlags is the -gcflags flag of the builds of the programs that compare the results of many
// generated parsers with the engine's (GeneratedParsersOutputs, GeneratedTypesMismatches): it
// compiles the packages of the program's module (codegentest/...) without optimizations and
// inlining. These builds compile thousands of generated packages and run each parser on a few
// inputs, so compiling dominates their cost, and the verdict compares results, which do not depend on
// the optimizations of the compiler. The library and the standard library stay optimized, as do the
// tests that measure allocations or retained memory of a generated parser, which build otherwise.
const CorpusGCFlags = "-gcflags=codegentest/...=-N -l"

// GoFlagsEnv is the GOFLAGS entry of the environment of a go command that builds generated programs.
var GoFlagsEnv = "GOFLAGS=" + GoFlags

// SetGoCache points the build cache of the go commands that the test process runs at a fresh
// directory and returns a function that removes it. Every test builds a different generated
// program, so the shared build cache would only accumulate entries that are never reused; a cache
// private to the test process still shares the builds of the standard library and of this module
// among the tests of a package.
//
// A process that is killed (a timeout, a signal, a full disk) cannot run the returned function, and
// its cache, which is gigabytes, would stay. The caches therefore live under one directory, each
// with a lock file that its process holds for as long as it runs; the kernel releases the lock when
// the process ends however it ends, so SetGoCache removes every cache whose lock it can take, which
// is exactly the cache of a dead process (unlike a recorded process ID, a lock cannot be confused
// with a reused one).
func SetGoCache() (remove func()) {
	root := filepath.Join(os.TempDir(), cacheRoot)
	if err := os.MkdirAll(root, 0o755); err != nil {
		panic(err)
	}
	reapCaches(root)
	dir, err := os.MkdirTemp(root, "c-")
	if err != nil {
		panic(err)
	}
	lock, err := holdLock(filepath.Join(dir, lockName))
	if err != nil {
		panic(err)
	}
	heldLocks = append(heldLocks, lock) // a collected file would close and so release its lock
	os.Setenv("GOCACHE", filepath.Join(dir, "cache"))
	return func() {
		os.RemoveAll(dir)
		lock.Close()
	}
}

// heldLocks are the lock files of the caches of this process.
var heldLocks []*os.File

// cacheRoot is the directory, in the temporary directory, that holds the build caches of the test
// processes, and lockName the file in each of them that its process locks.
const (
	cacheRoot = "sxir-gocache"
	lockName  = "owner.lock"
)

// graceAge is how old a cache directory without a lock file must be to be taken for a leaked one:
// a younger one may be between its creation and its lock.
const graceAge = 10 * time.Minute

// reapCaches removes the caches under root whose process has ended.
func reapCaches(root string) {
	if !locksWork {
		return
	}
	entries, _ := os.ReadDir(root)
	for _, e := range entries {
		dir := filepath.Join(root, e.Name())
		lock := filepath.Join(dir, lockName)
		if _, err := os.Stat(lock); err != nil {
			if info, ierr := e.Info(); ierr == nil && time.Since(info.ModTime()) > graceAge {
				os.RemoveAll(dir)
			}
			continue
		}
		if f, err := holdLock(lock); err == nil {
			os.RemoveAll(dir)
			f.Close()
		}
	}
}
