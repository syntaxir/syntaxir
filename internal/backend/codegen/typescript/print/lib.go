// The TypeScript library of generated parsers is the directory internal/backend/codegen/typescript/lib of this module, which
// TypeScript generation reads from GenOptions.TSLib: lib.ts, the library proper, and the modules
// that the generator places after it (libModules). Generation assembles them into one module, the
// lib.ts that parsers import.

// libModules are the files of the library that follow lib.ts in the generated module, with the
// heading that introduces each.
var libModules = []struct{ file, heading string }{
	{"budget.ts", "Invocation limit controls"},
	{"trace.ts", "Tracing"},
	{"profile.ts", "Profiling"},
}

// tsExportDecl matches an exported declaration of the library.
var tsExportDecl = regexp.MustCompile(`(?m)^export (?:abstract )?(function|class|const|let|interface|type) ([\p{L}\p{N}_$]+)`)

// tsLib is an assembled library: the text of the generated lib.ts and its exported names, mapped to
// whether they are only types.
type tsLib struct {
	text    string
	exports map[string]bool

	parseOnce sync.Once
	parse     *libParse
}

// libParsed returns the parse of the text of the library, made once. The bundles that shake a
// library all read the same text, and the parse is read-only, so they share it.
func (l *tsLib) libParsed() *libParse {
	l.parseOnce.Do(func() { l.parse = parseLib(l.text) })
	return l.parse
}

// libKey identifies an assembled library: its source, the features of the parsers it serves and the
// printed methods of its specialized compositions.
type libKey struct {
	fsys     fs.FS
	features common.FeatureSet
	methods  string
}

// libCache memoizes the assembled library of each key, as print keys its library cache: only a source
// whose dynamic type is a string or a pointer is a valid map key.
var libCache struct {
	mu  sync.Mutex
	lib map[libKey]*tsLib
}

// loadLib assembles the library of fsys for parsers with the features fs from lib, the compositions
// specialized for them (LibraryRequests), once per key (libKey).
func loadLib(fsys fs.FS, features common.FeatureSet, lib *library.Library) (*tsLib, error) {
	if fsys == nil {
		return nil, fmt.Errorf("TypeScript generation needs the library source: set GenOptions.TSLib")
	}
	ms, err := tsMethodsFor(lib)
	if err != nil {
		return nil, err
	}
	var key strings.Builder
	for _, m := range ms {
		key.WriteString(m.Name + "\x00" + m.Text + "\x00")
	}
	k := reflect.TypeOf(fsys).Kind()
	cacheable := k == reflect.String || k == reflect.Pointer
	lk := libKey{fsys, features, key.String()}
	libCache.mu.Lock()
	defer libCache.mu.Unlock()
	if cacheable {
		if lib, ok := libCache.lib[lk]; ok {
			return lib, nil
		}
	}
	out, err := assembleLib(fsys, features, ms)
	if err != nil {
		return nil, err
	}
	if cacheable {
		if libCache.lib == nil {
			libCache.lib = map[libKey]*tsLib{}
		}
		libCache.lib[lk] = out
	}
	return out, nil
}

// assembleLib returns the generated lib.ts of the library in fsys for parsers with the features fs:
// lib.ts after its marker, with the printed methods ms substituted, followed by libModules, narrowed
// to fs (narrowLib) unless fs has every feature, and the exported names of the result.
func assembleLib(fsys fs.FS, features common.FeatureSet, ms []tsMethod) (*tsLib, error) {
	read := func(name string) (string, error) {
		data, err := fs.ReadFile(fsys, name)
		return string(data), err
	}
	src, err := read(tsLibFileName)
	if err != nil {
		return nil, err
	}
	src = substituteMethods(src, ms)
	i := strings.Index(src, tsLibMarker)
	if i < 0 {
		return nil, fmt.Errorf("the TypeScript library's %s has no marker %q", tsLibFileName, strings.TrimSpace(tsLibMarker))
	}
	var b strings.Builder
	b.WriteString(TsGeneratedHeader())
	b.WriteString("// The library of the TypeScript parsers generated by sxir: nodes, errors, the parsing machine and\n")
	b.WriteString("// the controls of an invocation. It does not depend on a grammar; every parser imports it.\n\n")
	b.WriteString("/* eslint-disable */\n\n")
	b.WriteString(src[i+len(tsLibMarker):])
	for _, m := range libModules {
		text, err := read(m.file)
		if err != nil {
			return nil, err
		}
		b.WriteString("\n// --- " + m.heading + " ---\n")
		b.WriteString(text)
	}
	text := b.String()
	if features != common.FeatureSet(common.AllFeatures) {
		if text, err = narrowLib(text, features); err != nil {
			return nil, err
		}
	}
	lib := &tsLib{text: text, exports: map[string]bool{}}
	for _, m := range tsExportDecl.FindAllStringSubmatch(lib.text, -1) {
		// An interface merged with a class of the same name is a value.
		isType := m[1] == "interface" || m[1] == "type"
		if prev, ok := lib.exports[m[2]]; ok {
			isType = isType && prev
		}
		lib.exports[m[2]] = isType
	}
	return lib, nil
}

// LibText returns the text of the generated lib.ts of the library in fsys, with the compositions of
// lib specialized for every feature (LibraryRequests of common.AllFeatures).
func LibText(fsys fs.FS, lib *library.Library) (string, error) {
	out, err := loadLib(fsys, common.FeatureSet(common.AllFeatures), lib)
	if err != nil {
		return "", err
	}
	return out.text, nil
}

// LibFiles returns the file of the library alone, as LibOnly generates it, with the compositions of
// lib specialized for every feature (LibraryRequests of common.AllFeatures).
func LibFiles(fsys fs.FS, lib *library.Library) ([]common.GeneratedFile, error) {
	text, err := LibText(fsys, lib)
	if err != nil {
		return nil, err
	}
	return []common.GeneratedFile{{Path: tsLibFileName, Content: []byte(text)}}, nil
}
